def is_db_server_reachable(host, port, timeout=0.8):
    try:
        with socket.create_connection((host, int(port)), timeout=timeout):
            return True
    except (socket.timeout, ConnectionRefusedError, OSError):
        return False

use_sqlite_env = os.getenv('USE_SQLITE', 'False').lower() in ('true', '1', 'yes')
DB_NAME = os.getenv('DB_NAME', 'shopease_db')
DB_USER = os.getenv('DB_USER', 'root')
DB_PASSWORD = os.getenv('DB_PASSWORD', '')
DB_HOST = os.getenv('DB_HOST', 'localhost')
DB_PORT = os.getenv('DB_PORT', '3306')

if use_sqlite_env or not is_db_server_reachable(DB_HOST, DB_PORT):
    if not use_sqlite_env:
        print(f"[Shopease Info] MySQL server not detected at {DB_HOST}:{DB_PORT}. "
              f"Using SQLite database (db.sqlite3) for local development/testing. "
              f"To use MySQL, start MySQL service and create database '{DB_NAME}'.")
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.sqlite3',
            'NAME': BASE_DIR / 'db.sqlite3',
        }
    }
else:
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.mysql',
            'NAME': DB_NAME,
            'USER': DB_USER,
            'PASSWORD': DB_PASSWORD,
            'HOST': DB_HOST,
            'PORT': DB_PORT,
            'OPTIONS': {
                'charset': 'utf8mb4',
            },
        }
    }

